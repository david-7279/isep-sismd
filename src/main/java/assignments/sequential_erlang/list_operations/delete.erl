-module(delete).
-export([delete/2]).

delete(_, []) -> [];
delete(H, [H | T]) -> delete(H, T);
delete(X, [H | T]) -> [H | delete(X, T)].


%%%-------------------------------------------------------------------
%%% delete(3, [1,2,3,4])
%%%
%%% H = 1, X = 3 → diferentes
%%% [1 | delete(3, [2,3,4])]
%%%
%%% H = 2, X = 3 → diferentes
%%% [1, 2 | delete(3, [3,4])]
%%%
%%% H = 3, X = 3 → iguais
%%% delete(3, [4])]
%%%
%%% H = 4, X = 3 → diferentes
%%% [1, 2, 4 | delete(3, [])]
%%%
%%% delete(3, [])
%%%
%%% Resultado final: [1,2,4]
